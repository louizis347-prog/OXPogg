# ---------------------------------------------------------------- helpers
def Q(q, pt, opts, a, line, why):
    return dict(q=q, pt=pt, opts=[list(o) for o in opts], a=a, line=line, why=why)


def G(q, pt, opts, a, why):
    return dict(q=q, pt=pt, opts=list(opts), a=a, why=why)


def T(opts, a, why, q='Qual frase está certa?'):
    return dict(q=q, opts=list(opts), a=a, why=why)


def H(e, x, y, en, pt, say, sayPt):
    return dict(e=e, x=x, y=y, en=en, pt=pt, say=say, sayPt=sayPt)


def EXP(ic, en, tag, pt, use, ex, expt):
    return dict(ic=ic, en=en, tag=tag, pt=pt, use=use, ex=[ex, expt])


def RND(say, opts, a, why):
    return dict(fig='🎧', say=say, ask='Qual palavra você ouviu?', opts=list(opts), a=a, why=why)


def HP(say, opts, a, why):
    return dict(fig='🎧', say=say, ask='Ouça e toque na palavra.', opts=list(opts), a=a, why=why)


def HF(say, emojis, a, why):
    return dict(fig='🎧', say=say, ask='Ouça e toque na figura.', opts=[[e, ''] for e in emojis], a=a, why=why, pic=1)


def VBI(v, ic, pt, f1, f2, ex, expt, note):
    return dict(v=v, ic=ic, pt=pt, f=[['eu', f1], ['ele/ela', f2]], ex=[ex, expt], note=note)


def SL(cat, *opts):
    return dict(cat=cat, opts=[list(o) for o in opts])


def MOLD(label, slots, end=('.', '.')):
    return dict(label=label, slots=list(slots), end=list(end))


def PR(prompt, ph, chips, model, check, kw, tips, ok, reply):
    return dict(prompt=prompt, ph=ph, chips=chips, model=model, check=check, kw=kw,
                tips=[[list(p) for p in t] for t in tips], ok=ok, reply=list(reply))


def MIS(ic, name, desc, **d):
    return dict(ic=ic, name=name, desc=desc, data=PR(**d))


def CXI(text, pt, right, w1, w2):
    return dict(text=text, pt=pt, opts=[right, w1, w2], a=0)


def RSD(review, dquiz, rdg, pat, vplay, build, order, soundlab, produce, wrap, dictate):
    return dict(review=review, dquiz=dquiz, rdg=rdg, pat=pat, vplay=vplay, build=build, order=order,
                soundlab=soundlab, produce=produce, wrap=wrap, dictate=dictate,
                sbuild=build, balloons=pat, scene=review, scenebuild=vplay)


def pa(t, e, p, v=0):
    return dict(t=t, e=e, p=p, v=v)


